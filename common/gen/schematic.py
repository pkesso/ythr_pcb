"""Schematic writer: every symbol pin gets a local label with its net name (or a no-connect flag), symbols are
laid out in groups on a grid. Net names on the board are KiCad's: local label NAME -> net /NAME."""
import os
import sys

from .libs import SYMLIB, LIB, PCB
sys.path.insert(0, os.path.join(PCB, "tools"))
from kicad_gen import Uuids, sexpr, dump, kids, kid, q, f  # noqa: E402

GRID = 2.54


class SymLib:
    def __init__(self):
        t = sexpr(open(SYMLIB, encoding="utf-8").read(), keep_quotes=True)
        self.raw = {s[1].strip('"'): s for s in kids(t, "symbol")}
        self.pins = {}
        self.bbox = {}
        for name, s in self.raw.items():
            pins = []
            xs, ys = [0.0], [0.0]
            for u in kids(s, "symbol"):
                for p in kids(u, "pin"):
                    at = kid(p, "at")
                    hidden = "hide" in p or (kid(p, "hide") is not None and kid(p, "hide")[1] == "yes")
                    pins.append(dict(num=kid(p, "number")[1].strip('"'), x=float(at[1]), y=float(at[2]),
                                     a=float(at[3]) if len(at) > 3 else 0.0, type=p[1], hidden=hidden))
                    xs.append(float(at[1]))
                    ys.append(float(at[2]))
                for g in u:
                    if isinstance(g, list) and g[0] in ("rectangle", "polyline", "circle", "arc"):
                        for node in g:
                            if isinstance(node, list) and node[0] in ("start", "end", "center", "mid"):
                                xs.append(float(node[1]))
                                ys.append(float(node[2]))
                            if isinstance(node, list) and node[0] == "pts":
                                for xy in kids(node, "xy"):
                                    xs.append(float(xy[1]))
                                    ys.append(float(xy[2]))
            self.pins[name] = pins
            self.bbox[name] = (min(xs), min(ys), max(xs), max(ys))

    def lib_symbol(self, name):
        s = list(self.raw[name])
        s[1] = q(f"{LIB}:{name}")
        return dump(s)


def snap(v):
    return round(v / GRID) * GRID


def _prop(ids, ref, name, value, x, y, hide=False):
    h = " (hide yes)" if hide else ""
    return (f'(property {q(name)} {q(value)} (at {f(x)} {f(y)} 0){h} '
            f'(effects (font (size 1.27 1.27))))')


def write(design, path, root_uuid):
    lib = SymLib()
    ids = Uuids(root_uuid)
    parts = sorted(design.parts.values(), key=lambda p: (p.group, _refkey(p.ref)))
    # layout: groups in rows; each group's parts side by side
    W = 400.0
    x0, y0 = 25.4, 25.4
    cx, cy, row_h = x0, y0, 0.0
    placed = []
    groups = []
    for p in parts:
        if not groups or groups[-1][0] != p.group:
            groups.append((p.group, []))
        groups[-1][1].append(p)
    flags = [("PWR_FLAG", "GND"), ("PWR_FLAG", "+3V3")]
    for g, plist in groups + [("flags", flags)]:
        for p in plist:
            sym = p[0] if g == "flags" else p.cat["symbol"]
            bx0, by0, bx1, by1 = lib.bbox[sym]
            w = (bx1 - bx0) + 40
            h = (by1 - by0) + 15
            if cx + w > W:
                cx, cy, row_h = x0, cy + row_h, 0.0
            sx = snap(cx - bx0 + 20)
            sy = snap(cy + by1 + 7)
            placed.append((p, sym, sx, sy))
            cx += w
            row_h = max(row_h, h)
        cx, cy, row_h = x0, cy + row_h + 5, 0.0
    paper = "A3" if cy < 280 else "A2" if cy < 400 else "A1"

    out = [f'(kicad_sch (version 20231120) (generator "eeschema") (generator_version "8.0") (uuid {q(root_uuid)}) '
           f'(paper {q(paper)})',
           f'(title_block (title {q(design.title)}) (rev {q(design.rev)}) (company "YTHR") '
           f'(comment 1 "Generated by pcb/{design.name}/gen_{design.name}.py - do not edit"))',
           "(lib_symbols " + " ".join(lib.lib_symbol(s) for s in sorted({s for _, s, _, _ in placed})) + ")"]
    flag_n = 0
    for p, sym, sx, sy in placed:
        if isinstance(p, tuple):
            flag_n += 1
            ref, value, pins, fields = f"#FLG0{flag_n}", "PWR_FLAG", {"1": p[1]}, {}
            in_bom = "no"
            footprint = ""
        else:
            ref, value, pins = p.ref, p.val, p.pins
            footprint = f"{LIB}:{p.cat['footprint']}"
            fields = {"LCSC": p.cat["lcsc"]} if p.cat.get("lcsc") else {}
            in_bom = "yes" if p.cat.get("bom", True) else "no"
        bx0, by0, bx1, by1 = lib.bbox[sym]
        o = [f'(symbol (lib_id {q(LIB + ":" + sym)}) (at {f(sx)} {f(sy)} 0) (unit 1) (exclude_from_sim no) '
             f'(in_bom {in_bom}) (on_board {"no" if ref.startswith("#") else "yes"}) (dnp no) '
             f'(uuid {ids.q("symbol", ref, 1)})',
             _prop(ids, ref, "Reference", ref, sx, sy - by1 - 2.54, hide=ref.startswith("#")),
             _prop(ids, ref, "Value", value, sx, sy - by0 + 2.54),
             _prop(ids, ref, "Footprint", footprint, sx, sy, hide=True),
             _prop(ids, ref, "Datasheet", "" if isinstance(p, tuple) else p.cat["datasheet"], sx, sy, hide=True),
             _prop(ids, ref, "Description", "", sx, sy, hide=True)]
        for k, v in fields.items():
            o.append(_prop(ids, ref, k, v, sx, sy, hide=True))
        for pin in lib.pins[sym]:
            o.append(f'(pin {q(pin["num"])} (uuid {ids.q("pin", ref, 1, pin["num"])}))')
        o.append(f'(instances (project {q(design.name)} (path {q("/" + root_uuid)} (reference {q(ref)}) (unit 1))))')
        o.append(")")
        out.append(" ".join(o))
        # labels / no-connects at the pin ends
        seen = set()
        for pin in lib.pins[sym]:
            if pin["num"] in seen:
                continue
            seen.add(pin["num"])
            px, py = sx + pin["x"], sy - pin["y"]
            net = pins.get(pin["num"], "__missing__")
            if net == "__missing__":
                if pin["hidden"] or pin["type"] == "no_connect":
                    continue
                raise ValueError(f"{ref}: pin {pin['num']} has no net (use None for not connected)")
            if net is None:
                if pin["hidden"]:
                    continue
                out.append(f'(no_connect (at {f(px)} {f(py)}) (uuid {ids.q("nc", f(px), f(py))}))')
                continue
            ang = (pin["a"] + 180) % 360
            just = "left" if ang in (0, 90) else "right"
            out.append(f'(label {q(net)} (at {f(px)} {f(py)} {f(ang)}) (fields_autoplaced yes) '
                       f'(effects (font (size 1.27 1.27)) (justify {just} bottom)) (uuid {ids.q("label", f(px), f(py))}))')
    out.append('(sheet_instances (path "/" (page "1")))')
    out.append(")")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")


def _refkey(ref):
    import re
    m = re.match(r"([A-Z#]+)(\d+)", ref)
    return (m.group(1), int(m.group(2))) if m else (ref, 0)
